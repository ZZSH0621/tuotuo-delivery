// Reuse the actual 390px responsive stylesheet; no iframe or second application.
import postcss from 'postcss';
import {readFileSync,writeFileSync} from 'node:fs';
const files=['style.css','tuotuo.css','tuotuo-intro.css','tuotuo-saver.css','mobile-shell.css','reference-mobile.css','rounds.css'];
const output=postcss.root();
for(const file of files){
 const css=readFileSync(`public/${file}`,'utf8');
 // Legacy CSS has an EOF-closed media block; mirror browser recovery without editing it.
 const balance=(css.match(/\{/g)||[]).length-(css.match(/\}/g)||[]).length;
 const root=postcss.parse(css+'}'.repeat(Math.max(0,balance))); 
 root.walkAtRules('media',rule=>{
  let matches=true;
  const rest=rule.params.replace(/\((min|max)-width:\s*(\d+)px\)/g,(_,bound,n)=>{if(bound==='min'?390<+n:390>+n)matches=false;return '';}).replace(/^\s*and\s*|\s*and\s*$/g,'').trim();
  if(!matches){rule.remove();return;}
  if(!rest)rule.replaceWith(...rule.nodes);else rule.params=rest;
 });
 root.walkRules(rule=>{if(rule.parent.type==='atrule'&&/keyframes/.test(rule.parent.name))return;rule.selectors=rule.selectors.map(s=>/^(html|:root)(?=[\s.:#[]|$)/.test(s)?s.replace(/^(html|:root)/,'html.phonePreview'):`html.phonePreview ${s}`);});
 root.walkDecls(d=>{d.value=d.value.replace(/(-?\d*\.?\d+)vw\b/g,(_,n)=>`${Number((+n*3.9).toFixed(3))}px`);});
 output.append(root.nodes);
}
writeFileSync('public/tuotuo-portrait-responsive.css','/* Generated by scripts/generate-portrait-css.mjs. Exact 390px styles, scoped to desktop preview. */\n'+output.toString());
